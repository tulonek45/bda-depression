MODELS = {
    # baseline model: control
    "M0": "y ~ age_z + gender_female + income_z",
    # linear + non-linear model: habits + non-linear sleep
    "M1": "y ~ age_z + gender_female + income_z + vigorous_act + sedentary_z + alcohol_z + sleep_c + I(sleep_c ** 2) + smoking_former + smoking_current",
    # hierarchical model: (1 | age_group) and varying intercepts
    "M2": "y ~ gender_female + income_z + vigorous_act + sedentary_z + alcohol_z + sleep_c + I(sleep_c ** 2) + smoking_former + smoking_current + (1 | age_group)"
}

# Formatting the "y" column --> 5 categories to use with Bambi
def prepare_bambi_df(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    if "y" not in out.columns and "depression_status_int" in out.columns:
        out["y"] = out["depression_status_int"]
    out["y"] = pd.Categorical(out["y"], categories=[0, 1, 2, 3, 4], ordered=True)
    return out

# helper function to generate synthetic data before the preprocessed data is ready
def generate_synthetic_covariates(n, seed):
    rnd = np.random.default_rng(seed)

    smoking = rnd.choice(["never", "former", "current"], size=n, p=[0.6, 0.2, 0.2])

    synthetic_df = pd.DataFrame({
        "age_z": rnd.normal(0.0, 1.0, size=n),
        "gender_female": rnd.binomial(1, 0.5, size=n),
        "income_z": rnd.normal(0.0, 1.0, size=n),
        "vigorous_act": rnd.binomial(1, 0.45, size=n),
        "sedentary_z": rnd.normal(0.0, 1.0, size=n),
        "alcohol_z": np.clip(rnd.normal(0.0, 1.0, size=n), -0.8, 4.0),
        "sleep_c": np.clip(rnd.normal(0.0, 1.4, size=n), -4.5, 5.5),
        "smoking_former": (smoking == "former").astype(int),
        "smoking_current": (smoking == "current").astype(int),
        "age_group": rnd.choice(["18-29", "30-44", "45-59", "60+"], size=n),
        "y": rnd.integers(0, 5, size=n),
    })
    
    return prepare_bambi_df(synthetic_df)

# generate priors
# priors for the "thresholds" generated by bambi, checked from model print
def get_priors(include_sleep: bool = False, hierarchical: bool = False):
    priors = {
        # common Normal distribution prior
        "common": bmb.Prior("Normal", mu=0.0, sigma=0.5)
    }
    # add the following priors regarding the model
    if include_sleep:
        priors["I(sleep_c ** 2)"] = bmb.Prior("Normal", mu=0, sigma=0.1)
    if hierarchical:
        priors["1|age_group"] = bmb.Prior(
            "Normal", mu=0, sigma=bmb.Prior("Exponential", lam=1)
        )

    return priors

# blueprint function for building the different models
def build_model(model_name: str, df: pd.DataFrame):
    # dict for including sleep, hierarchical
    prior_dict = {
        "M0": [False, False],
        "M1": [True, False],
        "M2": [True, True],
    }
    # to include sleep, hierarchical
    sleep_included, hierarchical_included = prior_dict[model_name]
    # get priors
    priors = get_priors(sleep_included, hierarchical_included)

    # build model with bambi with "cumulative"
    model = bmb.Model(MODELS[model_name], data=prepare_bambi_df(df), family="cumulative", priors=priors)

    return model


